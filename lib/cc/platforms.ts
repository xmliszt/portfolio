export type PlatformId = (typeof PLATFORM_IDS)[number];

export const METRIC_FIELDS = [
  "views",
  "reach",
  "likes",
  "comments",
  "shares",
  "reposts",
  "quotes",
  "saves",
  "clicks",
  "profile_visits",
  "follows",
  "upvotes",
  "rank",
] as const;

export type MetricField = (typeof METRIC_FIELDS)[number];

export type Platform = {
  id: PlatformId;
  label: string;
  shortLabel: string;
  colorVar: string;
  /** Character limit on the main text, or `undefined` when the platform has none worth checking. */
  bodyLimit: number | undefined;
  /** Character limit on the title field, for platforms that have one. */
  titleLimit: number | undefined;
  maxHashtags: number;
  /** Metrics this platform shows, in the order the log form and Telegram print them. */
  metrics: readonly MetricField[];
  /** The platform's own name for a metric where it differs from the field name. */
  metricLabels: { [field in MetricField]?: string };
  composeUrl: string;
  postsFromPhone: boolean;
  /** `true` if the campaign planner never moves this platform's posts; `false` when it may. */
  plannerPinned: boolean;
  /** Where on the platform a post goes, stored in `posts.target`, or `undefined` when the platform has no such choice. */
  target: { label: string; placeholder: string } | undefined;
};

